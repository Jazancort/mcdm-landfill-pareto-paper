"""
generate_macros_r1.py  --  Generate R1 macros from r1_bootstrap.csv and r1_aggregate.csv
=========================================================================================
Reads results/r1/r1_bootstrap.csv and results/r1/r1_aggregate.csv and writes the
authoritative R1 macros. Replaces the manually copied values in macros.tex.

Source files (verified by SHA):
  r1_bootstrap.csv  -- bootstrap CIs for all R1 comparisons
  r1_aggregate.csv  -- Q2 per cell (kappa=200)

Usage: uv run python scripts/generate_macros_r1.py
"""

import hashlib, sys
from pathlib import Path
import pandas as pd

REPO   = Path(__file__).parent.parent
BOOT   = REPO / "results" / "r1" / "r1_bootstrap.csv"
AGG    = REPO / "results" / "r1" / "r1_aggregate.csv"
OUT    = REPO / "results" / "r1" / "macros_r1.tex"

for p in [BOOT, AGG]:
    if not p.exists():
        sys.exit(f"Missing: {p}")

sha_boot = hashlib.sha256(BOOT.read_bytes()).hexdigest()[:16]
sha_agg  = hashlib.sha256(AGG.read_bytes()).hexdigest()[:16]

df_boot = pd.read_csv(BOOT)
df_agg  = pd.read_csv(AGG)

def row(pair_substr):
    """Return the bootstrap row matching a substring of the pair column."""
    matches = df_boot[df_boot["pair"].str.contains(pair_substr, case=False, regex=False)]
    if len(matches) != 1:
        raise ValueError(f"Expected 1 row for '{pair_substr}', got {len(matches)}")
    return matches.iloc[0]

def agg(cell, assembly):
    matches = df_agg[(df_agg["cell"] == cell) & (df_agg["assembly"] == assembly)]
    if len(matches) != 1:
        raise ValueError(f"Expected 1 row for cell={cell} assembly={assembly}, got {len(matches)}")
    return float(matches.iloc[0]["Q2"])

# R-V* vs R-M (ref-set effect consistent coding)
r_rvm = row("R-V* vs R-M")
assert abs(r_rvm["diff_opt_pp"] - 0.0) < 0.01, "R-V* vs R-M opt != 0"
assert abs(r_rvm["diff_grd_pp"] - 11.8) < 0.05, "R-V* vs R-M grd != 11.8"

# R-asp vs R-V (residual ref-set effect, inconsistent coding)
# Note: values changed after aspect formula correction (2026-10-26)
# Old values (notebook convention): diff_opt=+4.0, diff_grd=+5.6
# New values (geographic formula):  diff_opt=-4.4, diff_grd=-3.8  (sign flipped)
r_asp_rv = row("R-asp vs R-V")

# R-V* vs R-asp (coding effect)
# Old: 76.0 pp (notebook convention, rasp_opt=24.0%)
# New: 84.4 pp (geographic formula, rasp_opt=15.6%)
r_coding = row("R-V* vs R-asp")

# R-asp aggregates
rasp_opt = agg("R_asp_Aprime", "optimal")
rasp_grd = agg("R_asp_Aprime", "greedy")

# R-V control: uses same score with 473-base normalization; aspect path unchanged
r_v_opt = agg("R_V_Aprime", "optimal")
r_v_grd = agg("R_V_Aprime", "greedy")

# Non-aspect diagonal cells: must be 100% (Proposition 1)
rvstar_opt = agg("RV_star_Aprime", "optimal")
rm_opt     = agg("RM_Aprime",      "optimal")

# Internal consistency assertions (values from geographic formula, 2026-10-26)
assert abs(rvstar_opt - 100.0) < 0.01, f"RV_star_Aprime diagonal != 100: {rvstar_opt}"
assert abs(rm_opt     - 100.0) < 0.01, f"RM_Aprime diagonal != 100: {rm_opt}"
assert abs(r_v_opt    -  20.0) < 0.5,  f"R-V opt changed unexpectedly: {r_v_opt} (expected ~20.0)"
assert abs(rasp_opt   -  15.6) < 0.5,  f"RaspOptimal regression: {rasp_opt} (expected ~15.6)"
assert abs(rasp_grd   -  15.8) < 0.5,  f"RaspGreedy  regression: {rasp_grd} (expected ~15.8)"
assert abs(rasp_opt + round(100 - rasp_opt, 1) - 100) < 0.01, "RaspOptimal + RaspLoss != 100 (one decimal)"

lines = [
    "% AUTO-GENERATED by scripts/generate_macros_r1.py -- DO NOT EDIT BY HAND",
    f"% source: r1_bootstrap.csv sha256={sha_boot}",
    f"% source: r1_aggregate.csv sha256={sha_agg}",
    "",
    "% R-asp descriptive",
    f"\\newcommand{{\\RaspOptimal}}{{{rasp_opt}}}   % R-asp opt: aspect continuous cell (%)",
    f"\\newcommand{{\\RaspGreedy}}{{{rasp_grd}}}   % R-asp grd (%)",
    f"\\newcommand{{\\RaspLoss}}{{{round(100-rasp_opt,1)}}}   % = 100 - \\RaspOptimal (one decimal; rounds to {int(round(100-rasp_opt))} integer)",
    "",
    "% R-V* vs R-M (reference-set effect, consistent coding)",
    f"\\newcommand{{\\RoneOneOptDelta}}{{{r_rvm['diff_opt_pp']}}}   % pp, optimal",
    f"\\newcommand{{\\RoneTwoGrdDelta}}{{{r_rvm['diff_grd_pp']}}}   % pp, greedy",
    f"\\newcommand{{\\RoneTwoGrdCIlo}}{{{r_rvm['ci_lo_grd']}}}   % 95% CI lower",
    f"\\newcommand{{\\RoneTwoGrdCIhi}}{{{r_rvm['ci_hi_grd']}}}   % 95% CI upper",
    "",
    "% R-asp vs R-V (residual reference-set effect, inconsistent coding)",
    f"\\newcommand{{\\ResidualRefOptDelta}}{{{r_asp_rv['diff_opt_pp']}}}   % pp, optimal",
    f"\\newcommand{{\\ResidualRefOptCIlo}}{{{r_asp_rv['ci_lo_opt']}}}",
    f"\\newcommand{{\\ResidualRefOptCIhi}}{{{r_asp_rv['ci_hi_opt']}}}",
    f"\\newcommand{{\\ResidualRefGrdDelta}}{{{r_asp_rv['diff_grd_pp']}}}   % pp, greedy",
    f"\\newcommand{{\\ResidualRefGrdCIlo}}{{{r_asp_rv['ci_lo_grd']}}}",
    f"\\newcommand{{\\ResidualRefGrdCIhi}}{{{r_asp_rv['ci_hi_grd']}}}   % was 7.6 in old text",
    "",
    "% R-V* vs R-asp (coding effect = 76 pp)",
    f"\\newcommand{{\\CodingEffectOpt}}{{{r_coding['diff_opt_pp']}}}   % pp",
    f"\\newcommand{{\\CodingEffectOptCIlo}}{{{r_coding['ci_lo_opt']}}}",
    f"\\newcommand{{\\CodingEffectOptCIhi}}{{{r_coding['ci_hi_opt']}}}",
    f"\\newcommand{{\\CodingEffectGrd}}{{{r_coding['diff_grd_pp']}}}",
    "",
]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {OUT}")

# Print diff against what is in macros.tex
print("\n=== Values vs macros.tex entries ===")
import re
macros_tex = (REPO / "macros.tex").read_text(encoding="utf-8")
checks = [
    ("RaspOptimal", rasp_opt),
    ("RaspLoss",    int(round(100-rasp_opt))),
    ("RoneOneOptDelta", r_rvm["diff_opt_pp"]),
    ("RoneTwoGrdDelta", r_rvm["diff_grd_pp"]),
    ("RoneTwoGrdCIlo",  r_rvm["ci_lo_grd"]),
    ("RoneTwoGrdCIhi",  r_rvm["ci_hi_grd"]),
    ("ResidualRefOptDelta", r_asp_rv["diff_opt_pp"]),
    ("ResidualRefOptCIlo",  r_asp_rv["ci_lo_opt"]),
    ("ResidualRefOptCIhi",  r_asp_rv["ci_hi_opt"]),
    ("ResidualRefGrdDelta", r_asp_rv["diff_grd_pp"]),
    ("ResidualRefGrdCIlo",  r_asp_rv["ci_lo_grd"]),
    ("ResidualRefGrdCIhi",  r_asp_rv["ci_hi_grd"]),
]
all_ok = True
for name, expected in checks:
    m = re.search(rf"\\newcommand{{\\{name}}}{{([^}}]+)}}", macros_tex)
    if m:
        actual = m.group(1)
        ok = abs(float(actual) - float(expected)) < 0.05
        status = "OK  " if ok else "DIFF"
        if not ok:
            all_ok = False
            print(f"  [{status}] \\{name}: macros.tex={actual}  csv={expected}")
        else:
            print(f"  [{status}] \\{name}={actual}")
    else:
        all_ok = False
        print(f"  [MISS] \\{name} not found in macros.tex")

print()
if all_ok:
    print("All R1 macros in macros.tex match r1_bootstrap.csv")
else:
    print("DIFFERENCES found — update macros.tex from generate_macros_r1.py output")
