# -*- coding: utf-8 -*-
"""
generate_macros_e6.py  --  Generate macros_e6.tex from e6_raw_prespec.csv.

Output: macros_e6.tex  (in repo root, alongside macros.tex)

Run:
    uv run python scripts/generate_macros_e6.py

Naming convention (aligns with macros.tex):
  - CamelCase, no standalone digits
  - Prefix: Esix (block), then P[one/two/three/four], then Descriptor, then Suffix
  - Family suffixes: Logn / Beta / Unif / Zinf / All
  - p-values stored as full expression: p<0.001 or p=0.053 (no bare number)

All statistics computed by e6_stats.py (single source of truth).
"""

import hashlib, json, subprocess
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import pandas as pd

# ── Statistics: single source of truth ───────────────────────────────────────
from e6_stats import (
    TOL,
    compute_all_stats as _compute_all_stats,
    check_invariants,
)

REPO = Path(__file__).parent.parent
SRC_CSV  = REPO / "results" / "e6" / "e6_raw_prespec.csv"
SENS_CSV = REPO / "results" / "e6" / "sensit" / "e6_raw_sensit_tvwF01954.csv"
OUT_TEX  = REPO / "macros_e6.tex"
OUT_JSON = REPO / "results" / "e6" / "e6_stats.json"

FAMILIES = ["lognormal", "beta13", "uniform", "zero_inflated"]
FAM_SUFFIX = {
    "lognormal":    "Logn",
    "beta13":       "Beta",
    "uniform":      "Unif",
    "zero_inflated":"Zinf",
}
N_REP = 30


def compute_all_stats(df):
    """Wrapper: remaps family-name keys to LaTeX suffix keys for write_macros."""
    raw = _compute_all_stats(df, FAMILIES)
    S = {"All": raw["All"]}
    for fam in FAMILIES:
        S[FAM_SUFFIX[fam]] = raw[fam]
    return S


# ── Formatting helpers ────────────────────────────────────────────────────────

def rnd(x, nd):
    """Half-up rounding on the true decimal representation (avoids float bias)."""
    return str(Decimal(repr(float(x))).quantize(Decimal(1).scaleb(-nd), ROUND_HALF_UP))


def fmt_p(p):
    """Format p-value as LaTeX string."""
    return r"p<0.001" if p < 0.001 else "p=" + rnd(p, 3)


def fmt_int(n):
    """Format integer with LaTeX thousands separator."""
    return f"{int(n):,}".replace(",", "{,}")


# ── Write macros_e6.tex ──────────────────────────────────────────────────────

def write_macros(S, sha, commit, target_tvw=None):
    lines = [
        "% AUTO-GENERATED by scripts/generate_macros_e6.py -- DO NOT EDIT BY HAND",
        f"% source: results/e6/e6_raw_prespec.csv  sha256={sha[:16]}",
        r"% Naming convention: CamelCase, \Esix prefix, family suffix (Logn/Beta/Unif/Zinf/All)",
        "% commit hash stored in results/e6/e6_stats.json (not here, to keep output deterministic)",
        "",
    ]

    def m(name, val, note=""):
        cmd = rf"\newcommand{{\{name}}}{{{val}}}"
        if note:
            cmd += f"  % {note}"
        lines.append(cmd)

    # --- Target TV_W for W_inf_F cell (pre-registered; from CSV target_tvw column) ---
    if target_tvw is not None:
        tvw_3dp = round(float(target_tvw), 3)
        m("EsixTargetTVW", f"{tvw_3dp:.3f}",
          "E6 pre-registered TV_W target (0.1986 rho_raw era; see DEV-E6-005)")
        lines.append("")

    # ── Design ──────────────────────────────────────────────────────────────
    lines.append("% ── Design ───────────────────────────────────────────────────────────")
    m("EsixNinst",    "120",           "total instances (4 families x 30 reps)")
    m("EsixNfam",     "4",             "number of marginal families")
    m("EsixNdraws",   fmt_int(24000),  "total draws (120 inst x 200 draws)")
    m("EsixPiZinf",   "0.90",          "zero-inflation rate for zero_inflated family")
    lines.append("")

    # ── P1 ──────────────────────────────────────────────────────────────────
    p1 = S["All"]["P1"]
    lines.append("% ── P1 ──────────────────────────────────────────────────────────────")
    m("EsixPoneHits",    fmt_int(p1["Hits"]),        "draws with TV_W=0 and Q2^opt=100%")
    m("EsixPoneTotal",   fmt_int(p1["Total"]),        "total M+B cell draws (= 2 x EsixNdraws)")
    m("EsixPoneNDesign", fmt_int(p1["Total"] // 2),  "draws per baseline cell (= 120 inst x 200 draws)")
    lines.append("")

    # ── P2 ──────────────────────────────────────────────────────────────────
    lines.append("% ── P2 (conservative; Poisson-binomial null) ───────────────────────")
    lines.append("% denominator = instances with loss>0 at some TV_W level (L/F/H)")
    lines.append("% primary count = L>=F>=H AND H<L (= monotone excl. 3-way ties)")
    lines.append("% null: p_i=1/6 (n_distinct=3), 1/3 (n_distinct=2), 0 (n_distinct=1)")
    for suf in [FAM_SUFFIX[f] for f in FAMILIES] + ["All"]:
        p2 = S[suf]["P2"]
        m(f"EsixPtwoLossyN{suf}",   str(p2["LossyN"]),    "instances with any loss")
        m(f"EsixPtwoMono{suf}",     str(p2["Mono"]),      "L>=F>=H AND H<L (monotone excl. 3-way ties)")
        m(f"EsixPtwoTies{suf}",     str(p2["Ties"]),      "3-way ties L=F=H (counted as failures)")
        m(f"EsixPtwoReversal{suf}", str(p2["Reversal"]),  "L>=F>=H fails")
        m(f"EsixPtwoStrictOnly{suf}", str(p2["StrictOnly"]),
          "sensitivity: n_distinct=3 AND L>=F>=H AND H<L")
        m(f"EsixPtwoP{suf}",        fmt_p(p2["P"]),
          "Poisson-binomial one-sided (mixed p_i=1/6 or 1/3)")
        lines.append("")

    # ── P3 ──────────────────────────────────────────────────────────────────
    lines.append("% ── P3 ──────────────────────────────────────────────────────────────")
    lines.append("% pre-registered: V_inf_F <= W_inf_F (TV_B agrava perda)")
    for suf in [FAM_SUFFIX[f] for f in FAMILIES] + ["All"]:
        p3 = S[suf]["P3"]
        m(f"EsixPthreePreregN{suf}",    str(p3["PreregN"]),     "instances meeting pre-registered criterion V<=W")
        m(f"EsixPthreeDenom{suf}",      str(p3["PreregDenom"]), "total instances tested (30 or 120)")
        m(f"EsixPthreeInfStrict{suf}",  str(p3["InfStrict"]),   "informative strict V<W")
        m(f"EsixPthreeInfDenom{suf}",   str(p3["InfDenom"]),    "informative denominator")
        m(f"EsixPthreeP{suf}",          fmt_p(p3["P"]),          "one-sided binomial p (informative)")
        lines.append("")

    # ── P4 ──────────────────────────────────────────────────────────────────
    lines.append("% ── P4 (bilateral; post hoc pooling across families = All) ─────────")
    lines.append("% deflate > inflate is the OPPOSITE of the prediction (DEV-E6-003)")
    for suf in [FAM_SUFFIX[f] for f in FAMILIES] + ["All"]:
        p4 = S[suf]["P4"]
        note_p = "two-sided binomial" + (", post hoc pooling (DEV-E6-003)" if suf == "All" else "")
        m(f"EsixPfourDefl{suf}",    str(p4["Defl"]),    "deflate>inflate strictly (OPPOSITE of prediction)")
        m(f"EsixPfourInfl{suf}",    str(p4["Infl"]),    "inflate>deflate strictly (prediction direction)")
        m(f"EsixPfourNonTied{suf}", str(p4["NonTied"]), "non-tied pairs (denominator for binomtest)")
        m(f"EsixPfourTied{suf}",    str(p4["Tied"]),    "tied pairs (excluded from binomtest)")
        m(f"EsixPfourP{suf}",       fmt_p(p4["P"]),     note_p)
        lines.append("")

    OUT_TEX.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  Written: {OUT_TEX}")


# ── Sensitivity macros (\EsixSens... prefix) ─────────────────────────────────

def write_sensitivity_macros(S_sens, sha_sens, target_tvw_sens):
    """Append \EsixSens... macros to OUT_TEX (sensitivity run, TW_F=0.1954)."""
    lines = [
        "",
        "% ── Sensitivity macros (DEV-E6-005; target TW_F=0.1954) ───────────────",
        "% AUTO-GENERATED by scripts/generate_macros_e6.py -- DO NOT EDIT BY HAND",
        f"% source: results/e6/sensit/e6_raw_sensit_tvwF01954.csv  sha256={sha_sens[:16]}",
        "",
    ]

    def m(name, val, note=""):
        cmd = rf"\newcommand{{\{name}}}{{{val}}}"
        if note:
            cmd += f"  % {note}"
        lines.append(cmd)

    # Target TV_W for the sensitivity run
    m("EsixSensTargetTVW", f"{target_tvw_sens:.4f}",
      "sensitivity run TW_F (rho_shift / Fogo corrected; DEV-E6-005)")
    lines.append("")

    # P4 (most important for §7.8 narrative)
    A = S_sens["All"]
    p4 = A["P4"]
    p4_prop = float(p4["Defl"]) / p4["NonTied"] if p4["NonTied"] > 0 else 0.0
    m("EsixSensPfourDeflAll",    str(p4["Defl"]),    "sensit: deflate>inflate strictly")
    m("EsixSensPfourInflAll",    str(p4["Infl"]),    "sensit: inflate>deflate strictly")
    m("EsixSensPfourNonTiedAll", str(p4["NonTied"]), "sensit: non-tied pairs (denominator)")
    m("EsixSensPfourTiedAll",    str(p4["Tied"]),    "sensit: tied pairs")
    m("EsixSensPfourPAll",       fmt_p(p4["P"]),     "sensit: two-sided binomial p-value")
    m("EsixSensPfourPropAll",    rnd(p4_prop, 2),    "sensit: deflate proportion (Defl/NonTied)")
    lines.append("")

    # P1 (same as principal — include for completeness)
    p1 = A["P1"]
    m("EsixSensPoneHits",  str(p1["Hits"]),  "sensit P1: draws on frontier")
    m("EsixSensPoneTotal", str(p1["Total"]), "sensit P1: total M+B draws")
    lines.append("")

    # P2 (pooled)
    p2 = A["P2"]
    m("EsixSensPtwoMonoAll",     str(p2["Mono"]),      "sensit P2: L>=F>=H AND H<L")
    m("EsixSensPtwoLossyNAll",   str(p2["LossyN"]),    "sensit P2: informative instances")
    m("EsixSensPtwoPAll",        fmt_p(p2["P"]),       "sensit P2: Poisson-binomial p")
    lines.append("")

    # P3 (pooled)
    p3 = A["P3"]
    m("EsixSensPthreePreregNAll",  str(p3["PreregN"]),     "sensit P3: V<=W instances")
    m("EsixSensPthreeDenomAll",    str(p3["PreregDenom"]), "sensit P3: denominator")
    m("EsixSensPthreeInfStrictAll", str(p3["InfStrict"]), "sensit P3: strict V<W")
    m("EsixSensPthreeInfDenomAll", str(p3["InfDenom"]),   "sensit P3: informative denom")
    m("EsixSensPthreePAll",        fmt_p(p3["P"]),        "sensit P3: one-sided binomial p")
    lines.append("")

    # Also generate the proportion macro for the principal run (for side-by-side)
    # (principal proportion computed separately in main())
    lines.append("% Principal P4 proportion (for side-by-side comparison in §7.8)")

    existing = OUT_TEX.read_text(encoding="utf-8")
    OUT_TEX.write_text(existing + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"  Appended \\EsixSens... macros to {OUT_TEX}")


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    print("generate_macros_e6.py")
    print(f"  Reading: {SRC_CSV}")
    df = pd.read_csv(SRC_CSV)
    sha = hashlib.sha256(SRC_CSV.read_bytes()).hexdigest()
    commit = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip()
    print(f"  CSV sha256: {sha[:16]}  commit: {commit}")
    print(f"  Rows: {len(df)}  inst_id: {df['inst_id'].nunique()}  families: {df['family'].nunique()}")

    S = compute_all_stats(df)
    check_invariants(S)
    # Extract target_tvw from CSV (added post-run; pre-registered run = 0.1986)
    target_tvw = None
    if "target_tvw" in df.columns:
        vals = df["target_tvw"].dropna().unique()
        assert len(vals) == 1, f"target_tvw has {len(vals)} distinct values: {vals}"
        target_tvw = float(vals[0])
        print(f"  target_tvw: {target_tvw:.4f} (3dp: {round(target_tvw,3):.3f})")
    write_macros(S, sha, commit, target_tvw=target_tvw)

    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    json.dump({"sha256": sha, "commit": commit,
               "stats": {k: {kk: {kkk: float(vvv) if isinstance(vvv, float) else vvv
                                   for kkk, vvv in vv.items()}
                              for kk, vv in v.items()}
                          for k, v in S.items()}},
              open(OUT_JSON, "w"), indent=2)
    print(f"  Written: {OUT_JSON}")

    A = S["All"]
    print()
    print("SUMMARY:")
    print(f"  P1: {A['P1']['Hits']}/{A['P1']['Total']} draws ({A['P1']['Hits']/A['P1']['Total']:.0%})")
    p2 = A["P2"]
    print(f"  P2: {p2['Mono']}/{p2['LossyN']} L>=F>=H AND H<L "
          f"({p2['Ties']} 3-way ties, {p2['Reversal']} reversal)  "
          f"{fmt_p(p2['P'])} (Poisson-binomial)")
    p4 = A["P4"]
    print(f"  P4: {p4['Defl']}/{p4['NonTied']} deflate>inflate "
          f"({p4['Tied']} tied)  {fmt_p(p4['P'])} two-sided")

    # ── Append principal P4 proportion + sensitivity macros ──────────────────
    # Principal P4 proportion (EsixPfourPropAll): Defl/NonTied
    p4_prop_prin = float(p4["Defl"]) / p4["NonTied"] if p4["NonTied"] > 0 else 0.0
    prop_line = (rf"\newcommand{{\EsixPfourPropAll}}{{{rnd(p4_prop_prin, 2)}}}"
                 "  % principal P4 proportion Defl/NonTied (for §7.8 side-by-side)")
    existing = OUT_TEX.read_text(encoding="utf-8")
    OUT_TEX.write_text(existing + "\n" + prop_line + "\n", encoding="utf-8")
    print(f"  Appended \\EsixPfourPropAll={rnd(p4_prop_prin, 2)}")

    # Sensitivity run
    if SENS_CSV.exists():
        print(f"\n  Reading sensitivity: {SENS_CSV.name}")
        df_sens = pd.read_csv(SENS_CSV)
        sha_sens = hashlib.sha256(SENS_CSV.read_bytes()).hexdigest()
        S_sens = compute_all_stats(df_sens)
        target_tvw_sens = float(df_sens["target_tvw"].dropna().unique()[0]) \
                          if "target_tvw" in df_sens.columns else 0.1954
        write_sensitivity_macros(S_sens, sha_sens, target_tvw_sens)
        p4s = S_sens["All"]["P4"]
        p4s_prop = float(p4s["Defl"]) / p4s["NonTied"] if p4s["NonTied"] > 0 else 0.0
        print(f"  Sensitivity P4: {p4s['Defl']}/{p4s['NonTied']}  p={p4s['P']:.6f}  prop={p4s_prop:.4f}")
    else:
        print(f"  Sensitivity CSV not found: {SENS_CSV}")


if __name__ == "__main__":
    main()
