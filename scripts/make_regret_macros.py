# -*- coding: utf-8 -*-
"""make_regret_macros.py — Generate the complete results/regret/regret_macros.tex.

Sources:
  - results/regret/regret_aggregate.csv  → SAW/TOPSIS mean R macros
  - results/regret/e1_oracle_per_draw.csv (SHA-verified) → E1 macros
  - Hardcoded bootstrap CIs for the grd-opt diff section (B=2000, seed=88,
    computed once and stable; see compute_regret.py bootstrap block).

Why a separate script (not compute_regret.py):
  compute_regret.py is the oracle that generates regret_perdraw.csv and
  regret_aggregate.csv; its SHA must remain stable to verify the output CSVs.
  This script is a lightweight post-processing step: reads those CSVs, reads
  the oracle CSV, and writes the LaTeX macros. It can be run at any time.

Usage (on Athena):
    MCDM_DATA_DIR=/home/julioazancort/scratch/mcdm \\
    .venv/bin/python3 scripts/make_regret_macros.py

Output: results/regret/regret_macros.tex  (overwritten)
"""
import hashlib
import math
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).parent.parent
OUT  = ROOT / "results" / "regret"

# ── SHA constants ─────────────────────────────────────────────────────────────
SHA_REGRET_AGG     = "bc364ce312ce9772f06d41fc63f0fc0b0991f6cc8665a52d82515283df952bd1"
SHA_REGRET_PERDRAW = "282445c4b5c5ccd593963ae1073210385da465b93fa45408e97ba3f5c99201ca"
SHA_E1_ORACLE_CSV  = "913396cea6a6288836783c9bc02a5f7a898b70643dd2788a5d0780b42155b56c"

# ── Verify input CSVs ─────────────────────────────────────────────────────────
agg_path  = OUT / "regret_aggregate.csv"
pd_path   = OUT / "regret_perdraw.csv"
e1_path   = OUT / "e1_oracle_per_draw.csv"

for path, sha_exp, name in [
    (agg_path,  SHA_REGRET_AGG,    "regret_aggregate.csv"),
    (pd_path,   SHA_REGRET_PERDRAW, "regret_perdraw.csv"),
    (e1_path,   SHA_E1_ORACLE_CSV, "e1_oracle_per_draw.csv"),
]:
    if not path.exists():
        raise RuntimeError(f"Input not found: {path}\n  Run compute_regret.py first.")
    got = hashlib.sha256(path.read_bytes()).hexdigest()
    if got != sha_exp:
        raise RuntimeError(
            f"SHA mismatch for {name}:\n"
            f"  expected {sha_exp}\n"
            f"  got      {got}"
        )
    print(f"  SHA OK: {name} ({sha_exp[:16]})", flush=True)

# ── SAW/TOPSIS macros from aggregate CSV ─────────────────────────────────────
df_agg = pd.read_csv(agg_path)

cell_map = {
    ("saw",    "minmax", "greedy"):  "RegrSAWmmGrd",
    ("saw",    "minmax", "optimal"): "RegrSAWmmOpt",
    ("saw",    "vector", "greedy"):  "RegrSAWvecGrd",
    ("saw",    "vector", "optimal"): "RegrSAWvecOpt",
    ("topsis", "minmax", "greedy"):  "RegrTOPSISmmGrd",
    ("topsis", "minmax", "optimal"): "RegrTOPSISmmOpt",
    ("topsis", "vector", "greedy"):  "RegrTOPSISvecGrd",
    ("topsis", "vector", "optimal"): "RegrTOPSISvecOpt",
}

macro_lines = [
    "% AUTO-GENERATED by scripts/make_regret_macros.py -- DO NOT EDIT BY HAND",
    "% R = (V_mm_opt - V_mm_selected) / (V_mm_opt - V_mm_worst_in_T)",
    "% Denominator: range over all 1.94M feasible trios (not just the 8 cells).",
    "% R in [0,1] by construction; R_pp = R * 100 (percentage of achievable value range).",
    "",
]

for _, row in df_agg.sort_values(["agg", "norm", "mont"]).iterrows():
    key  = (row["agg"], row["norm"], row["mont"])
    name = cell_map.get(key)
    if name is None:
        continue
    macro_lines.append(
        f"\\newcommand{{\\{name}}}{{{row['mean_R_pp']}}}  "
        f"% {row['agg']}/{row['norm']}/{row['mont']}: SE={row['se_R_pp']}"
    )
    macro_lines.append(
        f"\\newcommand{{\\{name}SE}}{{{row['se_R_pp']}}}  "
        f"% SE of R for {row['agg']}/{row['norm']}/{row['mont']}"
    )

# ── Differences grd-opt (bootstrap B=2000, seed=88, stable) ──────────────────
# These bootstrap CIs were computed once and are stable.
# To regenerate: run the bootstrap block in compute_regret.py with seed=88.
macro_lines += [
    "",
    "% \u2500\u2500 Differences grd-opt (paired bootstrap B=2000, seed=88) \u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500",
    "\\newcommand{\\RegrDiffSAWvec}{1.36}         % SAW vec: R(grd)-R(opt) (pp)",
    "\\newcommand{\\RegrDiffSAWvecLo}{0.95}       % CI lower",
    "\\newcommand{\\RegrDiffSAWvecHi}{1.74}       % CI upper",
    "\\newcommand{\\RegrDiffTOPSISvec}{2.15}      % TOPSIS vec: R(grd)-R(opt) (pp)",
    "\\newcommand{\\RegrDiffTOPSISvecLo}{1.74}    % CI lower",
    "\\newcommand{\\RegrDiffTOPSISvecHi}{2.58}    % CI upper",
    "\\newcommand{\\RegrDiffTOPSISmmGrdOpt}{0.86} % TOPSIS mm: R(grd)-R(opt) (pp)",
    "\\newcommand{\\RegrDiffTOPSISmmGrdOptLo}{0.56}",
    "\\newcommand{\\RegrDiffTOPSISmmGrdOptHi}{1.17}",
]

# ── E1 macros from oracle CSV ─────────────────────────────────────────────────
df_e1 = pd.read_csv(e1_path)

e1b_opt = df_e1[(df_e1["cell"] == "B") & (df_e1["mont"] == "optimal")]
e1b_grd = df_e1[(df_e1["cell"] == "B") & (df_e1["mont"] == "greedy")]
e1w_opt = df_e1[(df_e1["cell"] == "W") & (df_e1["mont"] == "optimal")]
e1w_grd = df_e1[(df_e1["cell"] == "W") & (df_e1["mont"] == "greedy")]

N_DRAWS    = len(e1b_opt)
e1b_mean   = f"{float(e1b_opt['R_pp'].mean()):.2f}"
e1b_se     = f"{float(e1b_opt['R_pp'].std(ddof=1)) / math.sqrt(N_DRAWS):.2f}"
e1b_med    = f"{float(e1b_opt['R_pp'].median()):.2f}"
e1b_grd_m  = f"{float(e1b_grd['R_pp'].mean()):.2f}"
e1w_mean   = f"{float(e1w_opt['R_pp'].mean()):.2f}"
e1w_grd_m  = f"{float(e1w_grd['R_pp'].mean()):.2f}"
e1b_max    = f"{float(e1b_opt['R_pp'].max()):.1f}"
n_zero     = int(e1b_opt["trio_eq_tstar"].sum())
frac_zero  = f"{n_zero / N_DRAWS * 100:.1f}"

# Bootstrap diff E1-B grd-opt (B=2000, seed=55, stable)
E1B_DIFF    = 3.72
E1B_DIFF_LO = 3.3
E1B_DIFF_HI = 4.1

macro_lines += [
    "",
    (f"% \u2500\u2500 E1 regret (oracle CSV e1_oracle_per_draw.csv "
     f"SHA={SHA_E1_ORACLE_CSV[:8]}; DEV-FOGO-E1B-001) \u2500\u2500"),
    "% New denominator (range over all T), so all values in [0,100%].",
    "% DEV-FOGO-E1B-001: fraction corrected 28% -> 35.4% (177/500 draws have trio==t*)",
    f"\\newcommand{{\\RegretEoneB}}{{{e1b_mean}}}            % E1-B/opt mean R (pp), SE={e1b_se}",
    f"\\newcommand{{\\RegretEoneBSE}}{{{e1b_se}}}",
    f"\\newcommand{{\\RegretEoneBMed}}{{{e1b_med}}}         % E1-B/opt median R (pp)",
    f"\\newcommand{{\\RegretEoneBGrd}}{{{e1b_grd_m}}}         % E1-B/grd mean R (pp)",
    f"\\newcommand{{\\RegretEoneW}}{{{e1w_mean}}}            % E1-W/opt mean R (pp)",
    f"\\newcommand{{\\RegretEoneBfracZero}}{{{frac_zero}}}    "
    f"% % of draws where E1-B/opt trio == t* (DEV-FOGO-E1B-001)",
    f"\\newcommand{{\\RegretEoneBfracZeroN}}{{{n_zero}}}       "
    f"% n draws (out of {N_DRAWS}) where E1-B/opt trio == t*",
    f"% Note: no draws exceed 100pp (max E1-B/opt R = {e1b_max} pp with new denominator)",
    "",
    "% \u2500\u2500 Random trio baseline \u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500",
    "% 2000 random valid trios, mean R averaged over 500 draws, seed=42.",
    "\\newcommand{\\RRegretRandom}{54}            % median R of random valid trio (pp)",
    "",
    "% \u2500\u2500 E1 greedy additional + grd-opt diff \u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500",
    f"\\newcommand{{\\RegretEoneWGrd}}{{{e1w_grd_m}}}          % E1-W/grd mean R (pp)",
    f"\\newcommand{{\\RegretEoneBGrdOptDiff}}{{{E1B_DIFF}}}   % E1-B grd-opt R diff (pp)",
    f"\\newcommand{{\\RegretEoneBGrdOptDiffLo}}{{{E1B_DIFF_LO}}}  % CI lower",
    f"\\newcommand{{\\RegretEoneBGrdOptDiffHi}}{{{E1B_DIFF_HI}}}  % CI upper",
]

# ── Write output ──────────────────────────────────────────────────────────────
out_path = OUT / "regret_macros.tex"
out_path.write_text("\n".join(macro_lines) + "\n", encoding="utf-8", newline="\n")
print(f"\nWrote: {out_path}")
print(f"  E1-B/opt: mean={e1b_mean} SE={e1b_se} med={e1b_med}")
print(f"  E1-W/opt: mean={e1w_mean}")
print(f"  frac_zero (trio==t*): {frac_zero}% ({n_zero}/{N_DRAWS})")
print()
print("Run: diff <(git show HEAD:results/regret/regret_macros.tex) results/regret/regret_macros.tex")
print("Expected diff: header comment only (AUTO-GENERATED by ... -> make_regret_macros.py)")
