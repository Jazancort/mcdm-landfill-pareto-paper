# -*- coding: utf-8 -*-
"""
generate_macros_e1.py  --  Generate E1-related macros from verified CSV.

Source: results/e1/e1_v3_verified.csv
  Reconstructed from data/e1_v3_rerun_20261002.log (commit 44f7ff5).
  Original run on Athena, 500 draws, eps=1e-9, float64.

Macros written:
  \\EoneVloss  = 100 - Q2_opt(E1-V)   = 43.2  (vector cell loss)
  \\EoneWloss  = 100 - Q2_opt(E1-W)   = 35.8  (within-group loss)

These are ORPHAN macros in macros.tex until this script is run and
the output is included. The verification commit is 44f7ff5.

Run:
    uv run python scripts/generate_macros_e1.py
"""
import hashlib
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).parent.parent
SRC  = ROOT / "results" / "e1" / "e1_v3_verified.csv"
OUT  = ROOT / "results" / "e1" / "e1_macros.tex"
OUT_JSON = ROOT / "results" / "e1" / "e1_stats.json"

EXPECTED = {
    "EoneVloss": 43.2,
    "EoneWloss": 35.8,
}


def main():
    if not SRC.exists():
        raise FileNotFoundError(f"Verified CSV not found: {SRC}")

    sha = hashlib.sha256(SRC.read_bytes()).hexdigest()
    df = pd.read_csv(SRC)

    def q2_opt(cell):
        row = df[(df["cell"] == cell) & (df["assembly"] == "optimal")]
        if len(row) == 0:
            raise ValueError(f"Cell {cell} not found in CSV")
        return float(row["Q2_pct"].iloc[0])

    eone_v = round(100.0 - q2_opt("E1-V"), 1)
    eone_w = round(100.0 - q2_opt("E1-W"), 1)

    # Assertions
    assert abs(eone_v - EXPECTED["EoneVloss"]) < 0.05, \
        f"EoneVloss {eone_v} != {EXPECTED['EoneVloss']}"
    assert abs(eone_w - EXPECTED["EoneWloss"]) < 0.05, \
        f"EoneWloss {eone_w} != {EXPECTED['EoneWloss']}"

    lines = [
        "% AUTO-GENERATED by scripts/generate_macros_e1.py -- DO NOT EDIT BY HAND",
        f"% source: results/e1/e1_v3_verified.csv  sha256={sha[:16]}",
        "% Original run: data/e1_v3_rerun_20261002.log (commit 44f7ff5, Athena, 500 draws)",
        "",
        rf"\newcommand{{\EoneVloss}}{{{eone_v}}}            % 100 - Q2_opt(E1-V) = vector cell loss",
        rf"\newcommand{{\EoneWloss}}{{{eone_w}}}            % 100 - Q2_opt(E1-W) = within-group loss",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Written: {OUT}")
    print(f"  EoneVloss = {eone_v}  (expected {EXPECTED['EoneVloss']})")
    print(f"  EoneWloss = {eone_w}  (expected {EXPECTED['EoneWloss']})")
    json.dump({"sha256": sha, "EoneVloss": eone_v, "EoneWloss": eone_w}, OUT_JSON.open("w"), indent=2)
    print(f"Written: {OUT_JSON}")


if __name__ == "__main__":
    main()
