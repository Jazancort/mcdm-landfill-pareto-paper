# -*- coding: utf-8 -*-
"""
generate_macros_f8.py  --  Generate F8 macros from f8_coincidence_v2.csv and f8_vec_frontier.csv.

Requires controls to have PASSED in _f8_vec_frontier_coincidence.py.
DO NOT run manually unless controls are confirmed.

Output: appended block to macros.tex (or macros_f8.tex — see OUT_TEX below).

Run:
    uv run python scripts/generate_macros_f8.py

Macros generated:
  \\FEightVecFrontierSize  -- |F_vec| under AHP weights (153)
  \\FEightVecCoinc         -- vec/vec greedy==optimal (457/500)
  \\FEightVecSubopt        -- vec/vec greedy!=optimal but both on frontier (43/500)
  \\FEightMMCoinc          -- vec/mm greedy==optimal (201/500)
  \\FEightMMSubopt         -- vec/mm greedy!=optimal (299/500)
"""

import hashlib
from pathlib import Path
import pandas as pd

REPO = Path(__file__).parent.parent
COINC_CSV  = REPO / "results" / "f8" / "f8_coincidence_v2.csv"
FRONT_CSV  = REPO / "results" / "f8" / "f8_vec_frontier.csv"
OUT_TEX    = REPO / "macros_f8.tex"   # separate file, included by main.tex

# ── Load and verify ──────────────────────────────────────────────────────────
print("generate_macros_f8.py")

if not COINC_CSV.exists():
    raise FileNotFoundError(f"Missing: {COINC_CSV}. Run _f8_vec_frontier_coincidence.py first.")
if not FRONT_CSV.exists():
    raise FileNotFoundError(f"Missing: {FRONT_CSV}. Run _f8_vec_frontier_coincidence.py first.")

df_coinc = pd.read_csv(COINC_CSV)
df_front = pd.read_csv(FRONT_CSV)
sha_coinc = hashlib.sha256(COINC_CSV.read_bytes()).hexdigest()
sha_front = hashlib.sha256(FRONT_CSV.read_bytes()).hexdigest()

N = len(df_coinc)
assert N == 500, f"Expected 500 draws, got {N}"

# Controls (must have been verified before running this script)
# C2-C5 are already embedded in the CSV: we verify q2 values
vv_opt_q2 = df_coinc['q2_vv_opt'].mean() * 100
vv_grd_q2 = df_coinc['q2_vv_grd'].mean() * 100
vm_opt_q2 = df_coinc['q2_vm_opt'].mean() * 100
vm_grd_q2 = df_coinc['q2_vm_grd'].mean() * 100

assert abs(vv_opt_q2 - 100.0) < 0.1, f"C: vec/vec/opt Q2={vv_opt_q2:.1f}% != 100%"
assert abs(vv_grd_q2 - 100.0) < 0.1, f"C: vec/vec/grd Q2={vv_grd_q2:.1f}% != 100%"
assert abs(vm_opt_q2 - 94.4) < 0.5,  f"C: vec/mm/opt Q2={vm_opt_q2:.1f}% != 94.4%"
assert abs(vm_grd_q2 - 72.4) < 0.5,  f"C: vec/mm/grd Q2={vm_grd_q2:.1f}% != 72.4%"
vm_div = int((df_coinc['q2_vm_opt'] != df_coinc['q2_vm_grd']).sum())
assert vm_div == 112, f"C: vec/mm divergence={vm_div} != 112"
print("  Controls: OK")

# ── Compute macros ───────────────────────────────────────────────────────────
n_front    = len(df_front)
vv_coinc   = int(df_coinc['vv_same'].sum())
vm_coinc   = int(df_coinc['vm_same'].sum())
vv_subopt  = N - vv_coinc
vm_subopt  = N - vm_coinc
assert vv_coinc + vv_subopt == N, f"vv: coinc+subopt={vv_coinc+vv_subopt} != N={N}"
assert vm_coinc + vm_subopt == N, f"vm: coinc+subopt={vm_coinc+vm_subopt} != N={N}"

print(f"  |F_vec|       = {n_front}")
print(f"  vv_coinc      = {vv_coinc}/{N}")
print(f"  vv_subopt     = {vv_subopt}/{N}")
print(f"  vm_coinc      = {vm_coinc}/{N}")
print(f"  vm_subopt     = {vm_subopt}/{N}")

# Breakdown: vm_div = 112, consisting of opt_on/grd_off (a) and opt_off/grd_on (b)
a = int(((df_coinc['q2_vm_opt'] == 1) & (df_coinc['q2_vm_grd'] == 0)).sum())
b = int(((df_coinc['q2_vm_opt'] == 0) & (df_coinc['q2_vm_grd'] == 1)).sum())
assert a + b == vm_div, f"a+b={a+b} != vm_div={vm_div}"
print(f"  vm_div breakdown: opt_on/grd_off={a}, opt_off/grd_on={b}")

# ── Write macros ─────────────────────────────────────────────────────────────
lines = [
    "% AUTO-GENERATED by scripts/generate_macros_f8.py -- DO NOT EDIT BY HAND",
    f"% source: f8_coincidence_v2.csv sha256={sha_coinc[:16]}",
    f"% source: f8_vec_frontier.csv sha256={sha_front[:16]}",
    "% Controls C1-C5 passed at generation time.",
    "",
    r"\newcommand{\FEightVecFrontierSize}{" + str(n_front) + r"}  % |F_vec| trios under AHP weights",
    r"\newcommand{\FEightVecCoinc}{"       + str(vv_coinc)  + r"}  % vec/vec greedy==optimal (same portfolio)",
    r"\newcommand{\FEightVecSubopt}{"      + str(vv_subopt) + r"}  % vec/vec greedy!=optimal (empirical; not covered by Theorem 1)",
    r"\newcommand{\FEightMMCoinc}{"        + str(vm_coinc)  + r"}  % vec/mm greedy==optimal",
    r"\newcommand{\FEightMMSubopt}{"       + str(vm_subopt) + r"}  % vec/mm greedy!=optimal",
    r"\newcommand{\FEightMMDivGrdOff}{"    + str(a)         + r"}  % vec/mm: opt ON, grd OFF (main pattern)",
    r"\newcommand{\FEightMMDivGrdOn}{"     + str(b)         + r"}  % vec/mm: grd ON, opt OFF (1 draw)",
    "",
]

OUT_TEX.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"  Written: {OUT_TEX}")

# ── Report text proposals ────────────────────────────────────────────────────
print()
print("PROPOSED TEXT §5.4 (replace lines 1122-1130 in main.tex):")
print(r"""
The $100\%$ under vec/greedy is empirical, not a consequence of
Theorem~\ref{thm:groupconst}: the greedy assembly and the exact solver
selected the same portfolio in \FEightVecCoinc{} of \ndraws{} draws;
in the remaining \FEightVecSubopt{} draws, the greedy rule returned
a different portfolio that nonetheless lay on the vector frontier.
""")
print()
print("  Remove the causal claim about perm dominance (lines 1126-1130).")
print("  Theorem 1 covers exact assembly only.")
