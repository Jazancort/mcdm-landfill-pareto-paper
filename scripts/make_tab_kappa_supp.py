# -*- coding: utf-8 -*-
"""
make_tab_kappa_supp.py  --  Supplementary Table: Q2 across 6 kappa x 8 cells.
Source: results/e7/e7_raw.csv
Output: results/e7/tab_kappa_supp.tex  (included via \input in supplementary)
"""
import pandas as pd
from pathlib import Path

ROOT = Path(__file__).parent.parent
df = pd.read_csv(ROOT / "results" / "e7" / "e7_raw.csv")

KAPPAS = [25, 50, 100, 200, 400, 1000]
CELLS = [
    ("saw",   "minmax", "greedy",  "SAW, mm, greedy"),
    ("saw",   "minmax", "optimal", "SAW, mm, optimal"),
    ("saw",   "vector", "greedy",  "SAW, vec, greedy"),
    ("saw",   "vector", "optimal", "SAW, vec, optimal"),
    ("topsis","minmax", "greedy",  "TOPSIS, mm, greedy"),
    ("topsis","minmax", "optimal", "TOPSIS, mm, optimal"),
    ("topsis","vector", "greedy",  "TOPSIS, vec, greedy"),
    ("topsis","vector", "optimal", "TOPSIS, vec, optimal"),
]

# Build table: rows = cells, cols = kappas
rows = []
for agg, norm, mont, label in CELLS:
    row = {"Cell": label}
    for k in KAPPAS:
        val = df.query(f"alpha=={k} and agg=='{agg}' and norm=='{norm}' and mont=='{mont}'")["nd_Q2Ap"].mean() * 100
        row[f"k={k}"] = f"{val:.1f}"
    rows.append(row)

out = []
out.append(r"% tab_kappa_supp.tex  --  AUTO-GENERATED by make_tab_kappa_supp.py")
out.append(r"% Source: results/e7/e7_raw.csv  (E7 authoritative run 2026-11-01)")
out.append(r"% Gates: 22/22 PASS; all values match Table~\ref{tab:factorial} at k=50 and k=200")
out.append(r"\begin{table*}[!t]")
out.append(r"\centering\small")
out.append(r"\caption{%")
out.append(r"  $Q_2[\mathcal{A}']$ (\%) across six values of the weight-concentration")
out.append(r"  parameter~$\kappa$ and eight $2^3$ cells.")
out.append(r"  At $\kappa=50$ and $\kappa=200$ values reproduce Table~\ref{tab:factorial}")
out.append(r"  (Gate G1, all 16 checks pass).")
out.append(r"  SAW\,/\,min-max\,/\,optimal is $100\%$ at every~$\kappa$ by")
out.append(r"  Proposition~\ref{prop:p1:stmt} (Gate G2).}")
out.append(r"\label{tab:e7grid}")
out.append(r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}l" + "c"*len(KAPPAS) + r"}")
out.append(r"\toprule")
out.append(r"Cell & " + " & ".join(f"$\\kappa={k}$" for k in KAPPAS) + r" \\")
out.append(r"\midrule")
for row in rows:
    vals = " & ".join(row[f"k={k}"] for k in KAPPAS)
    out.append(f"\\textit{{{row['Cell']}}} & {vals} \\\\")
out.append(r"\bottomrule")
out.append(r"\end{tabular*}")
out.append(r"\end{table*}")

tex = "\n".join(out) + "\n"
out_path = ROOT / "results" / "e7" / "tab_kappa_supp.tex"
out_path.write_text(tex, encoding="utf-8")
print(f"Saved: {out_path}")
print(tex)
