"""
generate_macros_raw_sens.py  --  Generate raw-sensitivity macros from CSV.
==========================================================================
Reads results/raw_sensitivity_4cells.csv (produced by raw_sensitivity_4cells.py)
and writes macros_raw_sens.tex.

Columns verified:
  SAW_optimal_same  SAW_greedy_same  TOPSIS_optimal_same  TOPSIS_greedy_same

Output macros (replacing manual entries in macros.tex):
  \\RawSensSawOptSame   \\RawSensSawGrdSame
  \\RawSensTopsisOptSame  \\RawSensTopsisGrdSame
  \\RawSensSame   (= SAW/opt, kept for backwards compat)
  \\RawSensTotal  (= 500)

Usage: uv run python scripts/generate_macros_raw_sens.py
"""

import hashlib
import subprocess
import sys
from pathlib import Path
import pandas as pd

REPO = Path(__file__).parent.parent
CSV  = REPO / "results" / "raw_sensitivity_4cells.csv"
OUT  = REPO / "macros_raw_sens.tex"

if not CSV.exists():
    sys.exit(f"Missing: {CSV}. Run scripts/raw_sensitivity_4cells.py first.")

# SHA-256 of source CSV
sha = hashlib.sha256(CSV.read_bytes()).hexdigest()

# Git commit at generation time
try:
    code_commit = subprocess.check_output(
        ["git", "describe", "--always", "--dirty"],
        cwd=REPO, text=True, stderr=subprocess.DEVNULL
    ).strip()
    if code_commit.endswith("-dirty"):
        print(f"WARNING: repo is dirty at generation time ({code_commit}).", flush=True)
except Exception:
    code_commit = "unknown"

df = pd.read_csv(CSV)
N  = len(df)
assert N == 500, f"Expected 500 draws, got {N}"

# Q2 per cell (fraction of draws where shift==raw portfolio)
saw_opt  = int(df["SAW_optimal_same"].sum())
saw_grd  = int(df["SAW_greedy_same"].sum())
top_opt  = int(df["TOPSIS_optimal_same"].sum())
top_grd  = int(df["TOPSIS_greedy_same"].sum())

print(f"  SAW  optimal shift==raw: {saw_opt}/{N}  ({saw_opt/N*100:.1f}%)")
print(f"  SAW  greedy  shift==raw: {saw_grd}/{N}  ({saw_grd/N*100:.1f}%)")
print(f"  TOPS optimal shift==raw: {top_opt}/{N}  ({top_opt/N*100:.1f}%)")
print(f"  TOPS greedy  shift==raw: {top_grd}/{N}  ({top_grd/N*100:.1f}%)")

# Sanity: all methods should give >= 90% coincidence
for label, val in [("SAW/opt", saw_opt), ("SAW/grd", saw_grd),
                   ("TOPSIS/opt", top_opt), ("TOPSIS/grd", top_grd)]:
    assert val >= 450, f"{label} coincidence {val}/500 < 90% — unexpected; verify CSV"

lines = [
    "% AUTO-GENERATED by scripts/generate_macros_raw_sens.py -- DO NOT EDIT BY HAND",
    f"% source: raw_sensitivity_4cells.csv sha256={sha[:16]}",
    f"% code_commit: {code_commit}",
    "",
    r"\newcommand{\RawSensSawOptSame}{"   + str(saw_opt) + r"}  % SAW/optimal shift==raw (true form)",
    r"\newcommand{\RawSensSawGrdSame}{"   + str(saw_grd) + r"}  % SAW/greedy shift==raw (true form)",
    r"\newcommand{\RawSensSame}{"         + str(saw_opt) + r"}  % SAW/optimal (kept for backwards compat)",
    r"\newcommand{\RawSensTotal}{"        + str(N)       + r"}  % total draws",
    r"\newcommand{\RawSensTopsisOptSame}{"+ str(top_opt) + r"}  % TOPSIS/optimal shift==raw",
    r"\newcommand{\RawSensTopsisGrdSame}{"+ str(top_grd) + r"}  % TOPSIS/greedy shift==raw",
    r"\newcommand{\RawSensTopsisOptDiff}{"+ str(N-top_opt)+r"}  % TOPSIS/optimal shift!=raw",
    r"\newcommand{\RawSensTopsisGrdDiff}{"+ str(N-top_grd)+r"}  % TOPSIS/greedy shift!=raw",
    "",
]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"\nWrote {OUT}  ({len(lines)} lines)")
print(f"  sha256(csv)={sha[:16]}  commit={code_commit}")
