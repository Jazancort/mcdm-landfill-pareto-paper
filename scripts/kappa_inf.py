# -*- coding: utf-8 -*-
"""kappa_inf.py — Compute Q2 for kappa->inf (deterministic AHP weights)."""
import sys
from pathlib import Path
import numpy as np

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from mcdm_experiment import (
    load_data, impute_nan, COL, AHP_WEIGHTS,
    haversine_km, MIN_DIST_KM, _build_decision_matrix, greedy_trio,
)
from pareto_utils import build_pareto_utils
from scoring import make_scorers

df_all, _, _ = load_data()
df_imp = impute_nan(df_all)
df_via = df_imp[df_imp[COL["protected"]] > 0].copy()
N = len(df_via)
assert N == 389, f"Expected 389, got {N}"

col_names = list(AHP_WEIGHTS.keys())
w = np.array(list(AHP_WEIGHTS.values()), dtype=np.float64)

D = haversine_km(df_via["latitude (degrees)"].values, df_via["longitude (degrees)"].values)
valid = D >= MIN_DIST_KM
trios = np.array(
    [(i,j,k) for i in range(N) for j in range(i+1,N) if valid[i,j]
     for k in range(j+1,N) if valid[i,k] and valid[j,k]], dtype=np.int32
)
T0, T1, T2 = trios[:,0], trios[:,1], trios[:,2]

compute_objs, is_dominated, _ = build_pareto_utils(df_via, col_names, trios)
X_via, benefit = _build_decision_matrix(df_via)
X_adj = X_via.copy()
for j, b in enumerate(benefit):
    if not b: X_adj[:,j] = 1.0 - X_via[:,j]
norms_via = np.maximum(np.sqrt((X_via**2).sum(0)), 1e-12)
saw_sc, topsis_sc = make_scorers(X_via, X_adj, norms_via, benefit)

def argmax_trio(sc):
    st = sc[T0] + sc[T1] + sc[T2]
    return trios[int(st.argmax())]

# Compute objectives for the deterministic weight vector
f1v, f2v, f3v = compute_objs(w)
F1 = f1v[T0] + f1v[T1] + f1v[T2]
F2 = f2v[T0] + f2v[T1] + f2v[T2]
F3 = f3v[T0] + f3v[T1] + f3v[T2]

CELLS = [
    ("saw",   "minmax", "greedy"), ("saw",   "minmax", "optimal"),
    ("saw",   "vector", "greedy"), ("saw",   "vector", "optimal"),
    ("topsis","minmax", "greedy"), ("topsis","minmax", "optimal"),
    ("topsis","vector", "greedy"), ("topsis","vector", "optimal"),
]

print(f"\n{'Cell':<30}  Q2(kappa=inf)")
print("-" * 45)
results = {}
for agg, norm, mont in CELLS:
    key = f"{agg}/{norm}/{mont}"
    sc = saw_sc(w, norm) if agg == "saw" else topsis_sc(w, norm)
    if mont == "greedy":
        trio = greedy_trio(sc, D)
    else:
        trio = argmax_trio(sc)
    q2 = int(not is_dominated(trio, F1, F2, F3))
    results[key] = q2 * 100
    print(f"  {key:<28}  {results[key]:.0f}%")

# Save macros for supplementary table
macro_lines = []
for agg, norm, mont in CELLS:
    key = f"{agg}/{norm}/{mont}"
    val = results[key]
    name = f"QtwoInf{'S' if agg=='saw' else 'T'}{norm.capitalize()[:2]}{mont.capitalize()[:3]}"
    macro_lines.append(f"\\newcommand{{\\{name}}}{{{val:.0f}}}")

macros_out = ROOT / "macros_kappa_inf.tex"
macros_out.write_text("\n".join([
    "% kappa=inf (deterministic AHP weights) Q2 values for supplementary table",
    "% Generated by scripts/kappa_inf.py",
    *macro_lines
]) + "\n", encoding="utf-8")
print(f"\nMacros saved to {macros_out.name}")
for line in macro_lines:
    print(" ", line)
