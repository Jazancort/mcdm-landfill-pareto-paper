# -*- coding: utf-8 -*-
"""check_macros_provenance.py — Verify macro provenance for make check.

Reads results/macros_provenance.csv (generated by generate_macros_provenance.py)
and checks that every \\MacroName used in the manuscript .tex files has an entry.

Also checks that no macro is defined but never used (orphan macros).

Exit 0 = all pass, exit 1 = any FAIL.

Usage:
    uv run python scripts/check_macros_provenance.py
"""
import sys
import re
import csv
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")

ROOT = Path(__file__).parent.parent
PROVENANCE_CSV = ROOT / "results" / "macros_provenance.csv"

TEX_FILES = [
    ROOT / "paper" / "manuscript" / "main.tex",
    ROOT / "paper" / "manuscript" / "santiago.tex",
    ROOT / "paper" / "manuscript" / "supplementary.tex",
]

SEP = "=" * 72
FAIL = []

# ─────────────────────────────────────────────────────────────────────────────
# §1  Load provenance
# ─────────────────────────────────────────────────────────────────────────────

def load_provenance():
    if not PROVENANCE_CSV.exists():
        FAIL.append(f"provenance CSV not found: {PROVENANCE_CSV}")
        print(f"  [FAIL] {PROVENANCE_CSV} not found — run generate_macros_provenance.py first")
        return {}
    with PROVENANCE_CSV.open(encoding="utf-8") as f:
        reader = csv.DictReader(f)
        return {row["macro"]: row for row in reader}

# ─────────────────────────────────────────────────────────────────────────────
# §2  Extract macro uses from .tex files
# ─────────────────────────────────────────────────────────────────────────────

# Match \MacroName (uppercase first letter = user-defined macro convention)
# Include digits in macro names (e.g. \EoneBGrdF1Percentile)
_USE_RE = re.compile(r'\\([A-Z][A-Za-z0-9]+)')

# Match \newcommand{\MacroName} definitions (to exclude from "used" set)
_DEF_RE = re.compile(r'\\(?:re)?newcommand\{\\([A-Za-z]+)\}')

# LaTeX built-in commands to ignore
_BUILTINS = {
    "FloatBarrier", "LaTeX", "TeX", "BibTeX", "MakeUppercase",
    "Pr", "Re", "Im", "S", "P", "L", "O", "C", "N", "Z", "Q", "R",
    "T", "E", "F", "G", "H", "I", "J", "K", "M", "U", "V", "W", "X", "Y",
    # Math operators
    "Delta", "Lambda", "Sigma", "Omega", "Gamma", "Theta", "Pi", "Phi",
    "Psi", "Xi", "Upsilon", "Alpha", "Beta",
    "Rightarrow", "Leftarrow", "Leftrightarrow", "Longrightarrow",
    "Longleftarrow", "Longleftrightarrow",
    # CAS class commands
    "WriteBookmarks",
    # Section sign \S followed by digit (e.g. \S2, \S3 in citations)
    "S2", "S3", "S4", "S5", "S6", "S7", "S8", "S9",
    # Defined in main.tex preamble
    "Aspace", "Sites", "Tset", "Fset",
    "CR", "lmax",
    "eqmargin", "devvec", "topsisexp", "siglevel",
    "wahp", "wsc", "wob", "wfr",
    "argmax",
    "Ncells", "Ncellsnet",
    "TVrnk",  # defined in macros_amplitudes.tex
}

# Macros defined in main.tex preamble (not in macros files)
_PREAMBLE_MACROS = {
    "Ncells", "Ncellsnet", "CR", "lmax", "wahp", "wsc", "wob", "wfr",
    "argmax", "eqmargin", "devvec", "topsisexp", "siglevel", "Aspace", "Sites",
}

def extract_used_macros(tex_files):
    used = set()
    for path in tex_files:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        # Remove comment lines
        text_no_comments = re.sub(r'%[^\n]*', '', text)
        for m in _USE_RE.finditer(text_no_comments):
            name = m.group(1)
            if name not in _BUILTINS and name not in _PREAMBLE_MACROS:
                used.add(name)
    return used

# ─────────────────────────────────────────────────────────────────────────────
# §3  Main
# ─────────────────────────────────────────────────────────────────────────────

print(SEP)
print("check_macros_provenance.py")
print(SEP)

provenance = load_provenance()
if not provenance:
    print(f"\n[FAIL] Cannot check provenance — CSV missing")
    sys.exit(1)

print(f"\n  Loaded {len(provenance)} macro definitions from provenance CSV")

used_macros = extract_used_macros(TEX_FILES)
print(f"  Found {len(used_macros)} distinct macro uses in manuscript")

# Check: every used macro has provenance
missing = sorted(m for m in used_macros if m not in provenance and m not in _PREAMBLE_MACROS)
if missing:
    print(f"\n[FAIL] {len(missing)} macros used but not in provenance CSV:")
    for m in missing[:30]:
        print(f"  \\{m}")
    if len(missing) > 30:
        print(f"  ... and {len(missing)-30} more")
    FAIL.append(f"{len(missing)} macros without provenance")
else:
    print(f"  [OK  ] All used macros have provenance entries")

# Check: orphan macros (defined but never used)
# Only report as WARN, not FAIL (some macros are used in supplementary or conditionally)
defined = set(provenance.keys())
orphans = sorted(defined - used_macros - _PREAMBLE_MACROS)
if orphans:
    print(f"\n[WARN] {len(orphans)} macros defined but not found in manuscript scan:")
    for m in orphans[:20]:
        src = provenance[m]["source_tex"]
        print(f"  \\{m}  ({src})")
    if len(orphans) > 20:
        print(f"  ... and {len(orphans)-20} more")
else:
    print(f"  [OK  ] No orphan macros found")

print()
print(SEP)
if FAIL:
    print(f"FAILED: {len(FAIL)} check(s):")
    for f in FAIL:
        print(f"  x {f}")
    sys.exit(1)
else:
    print("ALL CHECKS PASSED")
    sys.exit(0)
